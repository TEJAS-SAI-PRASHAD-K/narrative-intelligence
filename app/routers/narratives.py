"""Narratives -- the first pillar and the product's centre of gravity.

Two rules enforced here rather than in the UI:

* ``PATCH`` sets ``edited_by_user``, and a reclustering run must never overwrite
  an edited title. The enforcement lives in ``app/tasks/nlp.py`` and there is a
  test for it, but the flag is set here.
* ``/score`` never returns a bare number. It returns the score, the three
  components, the weights that were applied, whether they were renormalized, and
  the formula version. A number the UI cannot explain in one click is a failed
  requirement.
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends, Query, Response, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.db import get_session
from app.deps import Filters, Pagination, RequireRead, RequireWrite, rate_limit
from app.errors import NotFound
from app.mock import responses as mock
from app.schemas.actors import AuthorOut
from app.schemas.common import JobAccepted, PageResponse
from app.schemas.compass import (
    CompassContext,
    CompassFeedback,
    CompassFeedbackResult,
)
from app.schemas.narratives import (
    NarrativeCohortShare,
    NarrativeCreate,
    NarrativeDetail,
    NarrativeFreshness,
    NarrativeScoreExplanation,
    NarrativeSummary,
    NarrativeTimeline,
    NarrativeUpdate,
)
from app.schemas.posts import PostOut

router = APIRouter(prefix="/narratives", tags=["narratives"], dependencies=[Depends(rate_limit)])
compass_router = APIRouter(prefix="/compass", tags=["compass"], dependencies=[Depends(rate_limit)])


def _demo_narrative(narrative_id: str):
    narrative = mock.corpus().by_narrative.get(narrative_id)
    if narrative is None:
        raise NotFound(f"No narrative with id {narrative_id}.", code="narrative_not_found")
    return narrative


