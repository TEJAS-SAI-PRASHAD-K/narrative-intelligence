@router.get(
    "/{narrative_id}/compass",
    response_model=CompassContext,
    summary="Compass Context for a narrative",
    description=(
        "A RAG-generated, mandatorily-cited analyst note. When retrieval could not "
        "source the claim, `verification_status` is `insufficient_evidence` and "
        "`context` is an empty string -- an empty field is honest where an uncited "
        "paragraph is not."
    ),
)
async def narrative_compass(
    narrative_id: str,
    principal: RequireRead,
    session: Annotated[AsyncSession, Depends(get_session)],
) -> CompassContext:
    if mock.demo_mode():
        context = mock.compass_context(_demo_narrative(narrative_id))
        if context is None:
            raise NotFound(
                "No Compass Context has been generated for this narrative yet.",
                code="compass_context_not_found",
                detail={"narrative_id": narrative_id, "hint": "POST .../compass/regenerate"},
            )
        return context
    from app.repositories.compass import latest_context

    return await latest_context(session, narrative_id)


