@compass_router.post(
    "/{context_id}/feedback",
    response_model=CompassFeedbackResult,
    summary="Rate a Compass Context",
    description="Thumbs up/down, stored for the writeup's error analysis.",
)
async def compass_feedback(
    context_id: str,
    body: CompassFeedback,
    principal: RequireWrite,
    session: Annotated[AsyncSession, Depends(get_session)],
) -> CompassFeedbackResult:
    if mock.demo_mode():
        return CompassFeedbackResult(
            context_id=context_id,
            recorded=True,
            helpful_count=7 + (1 if body.helpful else 0),
            unhelpful_count=2 + (0 if body.helpful else 1),
        )
    from app.repositories.compass import record_feedback

    return await record_feedback(session, context_id, body, actor=principal.name)
